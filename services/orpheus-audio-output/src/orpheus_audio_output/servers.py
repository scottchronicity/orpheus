"""Audio servers: the process that turns an output endpoint into a playable sink.

A server implementation owns its daemon's startup, availability, health and
recovery, maps an output ``Endpoint`` to one of its sinks, and routes playback
there. ``capabilities`` lists what it can provide to outputs (see
``outputs.BluetoothOutput.requires``).
"""

from __future__ import annotations

import os
import re
import subprocess
import time
from dataclasses import dataclass, field
from pathlib import Path
from typing import Callable, FrozenSet, Optional

from .commands import CommandResult, CommandRunner, RunAs
from .config import AudioOutputConfig, AudioOutputConfigError
from .outputs import BLUETOOTH_A2DP, Endpoint

READY = "ready"
STARTING = "starting"
STOPPED = "stopped"
FAILED = "failed"
ISOLATION_VIOLATION = "isolation_violation"

# Modules that open ALSA devices. The managed server never loads them, so it
# cannot take the USB capture interface the recording agents read with ALSA.
_CAPTURE_RISK_MODULES = re.compile(r"^module-(alsa-\S*|udev-detect|detect|oss|jack\S*)$")


@dataclass(frozen=True)
class ServerState:
    state: str
    detail: str = ""
    managed: Optional[bool] = None  # True: our process; False: adopted; None: none
    pid: Optional[int] = None

    @property
    def ready(self) -> bool:
        return self.state == READY


@dataclass
class _Child:
    proc: subprocess.Popen
    started: float
    exit_code: Optional[int] = None
    extra: dict = field(default_factory=dict)


class AudioServer:
    """Implementation boundary for audio servers (PulseAudio now; PipeWire/ALSA later)."""

    type: str = ""
    capabilities: FrozenSet[str] = frozenset()

    def ensure(self) -> ServerState:  # pragma: no cover - interface
        """Check the server; start or restart it if needed. Returns its state."""
        raise NotImplementedError

    def find_sink(self, endpoint: Endpoint) -> Optional[str]:  # pragma: no cover
        raise NotImplementedError

    def default_sink(self) -> Optional[str]:  # pragma: no cover
        raise NotImplementedError

    def route_to(self, sink: str) -> tuple[bool, str]:  # pragma: no cover
        raise NotImplementedError

    def isolation_violations(self) -> list[str]:  # pragma: no cover
        raise NotImplementedError

    def restart(self, reason: str) -> None:  # pragma: no cover
        raise NotImplementedError

    def stop(self) -> None:  # pragma: no cover
        raise NotImplementedError

    def describe(self) -> dict:  # pragma: no cover
        raise NotImplementedError


def pulseaudio_script(capabilities: FrozenSet[str]) -> str:
    """The startup script for the managed PulseAudio: only what outputs need."""
    lines = [
        "# Generated by orpheus-audio-output. Never add ALSA/udev modules here:",
        "# this server must not open the capture interface used by the recording",
        "# agents. Playback reaches it over the native protocol socket.",
        ".fail",
        "load-module module-native-protocol-unix",
    ]
    if BLUETOOTH_A2DP in capabilities:
        lines += [
            "load-module module-bluetooth-policy",
            "load-module module-bluetooth-discover",
        ]
    return "\n".join(lines) + "\n"


class PulseAudioServer(AudioServer):
    """A PulseAudio instance for one user, at that user's standard socket.

    The socket is ``/run/user/<uid>/pulse/native``, which is where the playback
    agent (running as that user) already connects. If a PulseAudio is already
    answering there (a desktop session, a manual start), it is adopted rather
    than replaced: routing works against it, and it is never stopped.
    """

    type = "pulseaudio"
    capabilities = frozenset({BLUETOOTH_A2DP})

    def __init__(
        self,
        user: str,
        needs: FrozenSet[str],
        runner: Optional[CommandRunner] = None,
        *,
        pulseaudio_bin: str = "pulseaudio",
        pactl_bin: str = "pactl",
        runtime_root: Path = Path("/run/user"),
        script_dir: Path = Path("/run/orpheus-audio-output"),
        proc_root: Path = Path("/proc"),
        startup_timeout: float = 10.0,
        command_timeout: float = 5.0,
        clock: Callable[[], float] = time.monotonic,
        sleep: Callable[[float], None] = time.sleep,
        resolve_user: Callable[[str], RunAs] = RunAs.for_user,
    ) -> None:
        self.user = user
        self._needs = frozenset(needs)
        self._runner = runner or CommandRunner()
        self._pulseaudio_bin = pulseaudio_bin
        self._pactl_bin = pactl_bin
        self._runtime_root = Path(runtime_root)
        self._script_dir = Path(script_dir)
        self._proc_root = Path(proc_root)
        self._startup_timeout = startup_timeout
        self._command_timeout = command_timeout
        self._clock = clock
        self._sleep = sleep
        self._resolve_user = resolve_user
        self._run_as: Optional[RunAs] = None
        self._child: Optional[_Child] = None
        self.starts = 0
        self.last_exit: Optional[int] = None
        self.notes: list[str] = []

    # -- identity ---------------------------------------------------------
    def _identity(self) -> Optional[RunAs]:
        if self._run_as is None:
            try:
                self._run_as = self._resolve_user(self.user)
            except KeyError:
                return None
        return self._run_as

    @property
    def runtime_dir(self) -> Optional[Path]:
        ident = self._identity()
        return self._runtime_root / str(ident.uid) if ident else None

    @property
    def socket(self) -> Optional[Path]:
        rd = self.runtime_dir
        return rd / "pulse" / "native" if rd else None

    def _env(self) -> dict[str, str]:
        ident = self._identity()
        assert ident is not None
        return {
            "HOME": ident.home,
            "USER": ident.user,
            "LOGNAME": ident.user,
            "XDG_RUNTIME_DIR": str(self.runtime_dir),
            # Explicit server: clients never autospawn a stock PulseAudio
            # (which would load module-udev-detect and take the capture card).
            "PULSE_SERVER": f"unix:{self.socket}",
            "PATH": os.environ.get("PATH", "/usr/local/bin:/usr/bin:/bin"),
            "LANG": "C",
        }

    def _pactl(self, *args: str) -> CommandResult:
        return self._runner.run(
            [self._pactl_bin, *args],
            timeout=self._command_timeout,
            run_as=self._identity(),
            env=self._env(),
        )

    def _answering(self) -> bool:
        sock = self.socket
        if sock is None or not sock.exists():
            return False
        return self._pactl("info").ok

    # -- lifecycle --------------------------------------------------------
    def _child_alive(self) -> bool:
        if self._child is None:
            return False
        code = self._child.proc.poll()
        if code is None:
            return True
        self.last_exit = code
        self._child = None
        return False

    def _ensure_runtime_dir(self) -> None:
        ident = self._identity()
        assert ident is not None
        rd = self.runtime_dir
        assert rd is not None
        if rd.is_dir():
            return
        # Normally created by systemd-logind (the installer enables lingering
        # for this user so it exists from boot, independent of logins).
        rd.mkdir(mode=0o700, parents=True, exist_ok=True)
        try:
            os.chown(rd, ident.uid, ident.gid)
        except PermissionError:
            pass
        self.notes.append(f"created missing runtime directory {rd} (is lingering enabled?)")

    def _write_script(self) -> Path:
        self._script_dir.mkdir(parents=True, exist_ok=True)
        path = self._script_dir / "pulseaudio.pa"
        path.write_text(pulseaudio_script(self._needs))
        path.chmod(0o644)
        return path

    def _spawn(self) -> _Child:
        ident = self._identity()
        assert ident is not None
        script = self._write_script()
        argv = [
            self._pulseaudio_bin,
            "--daemonize=no",
            "--exit-idle-time=-1",
            "--disallow-exit=yes",
            "--realtime=no",
            "--log-target=stderr",
            "-n",
            "-F",
            str(script),
        ]
        kwargs: dict = {}
        if os.geteuid() != ident.uid:
            kwargs.update(user=ident.uid, group=ident.gid)
            try:
                kwargs["extra_groups"] = os.getgrouplist(ident.user, ident.gid)
            except (KeyError, OSError):
                pass
        proc = subprocess.Popen(
            argv, stdin=subprocess.DEVNULL, env=self._env(), cwd=ident.home, **kwargs
        )
        self.starts += 1
        return _Child(proc=proc, started=self._clock())

    def ensure(self) -> ServerState:
        if self._identity() is None:
            return ServerState(FAILED, f"user {self.user!r} does not exist")

        if self._child_alive():
            assert self._child is not None
            pid = self._child.proc.pid
            if self._answering():
                return ServerState(READY, managed=True, pid=pid)
            self._terminate("not answering on its socket")
            return ServerState(FAILED, f"PulseAudio (pid {pid}) stopped answering", managed=True)

        if self._answering():
            return ServerState(READY, "adopted a PulseAudio already running for this user", False)

        exit_note = (
            f"; previous instance exited with code {self.last_exit}" if self.last_exit else ""
        )
        try:
            self._ensure_runtime_dir()
            self._child = self._spawn()
        except OSError as exc:
            return ServerState(FAILED, f"could not start PulseAudio: {exc}")

        deadline = self._clock() + self._startup_timeout
        while self._clock() < deadline:
            if not self._child_alive():
                # Lost a race with another instance for this user? Adopt it.
                if self._answering():
                    return ServerState(READY, "adopted a PulseAudio already running", False)
                return ServerState(
                    FAILED, f"PulseAudio exited during startup with code {self.last_exit}"
                )
            if self._answering():
                assert self._child is not None
                return ServerState(
                    READY, f"started{exit_note}", managed=True, pid=self._child.proc.pid
                )
            self._sleep(0.5)
        self._terminate("did not answer within the startup timeout")
        return ServerState(FAILED, f"PulseAudio did not answer within {self._startup_timeout:g}s")

    def _terminate(self, reason: str) -> None:
        child, self._child = self._child, None
        if child is None:
            return
        self.notes.append(f"stopping PulseAudio (pid {child.proc.pid}): {reason}")
        if child.proc.poll() is None:
            child.proc.terminate()
            try:
                child.proc.wait(timeout=5)
            except subprocess.TimeoutExpired:
                child.proc.kill()
                child.proc.wait(timeout=5)
        self.last_exit = child.proc.returncode

    def restart(self, reason: str) -> None:
        self._terminate(reason)

    def stop(self) -> None:
        self._terminate("manager stopping")

    @property
    def managed_pid(self) -> Optional[int]:
        return self._child.proc.pid if self._child and self._child.proc.poll() is None else None

    # -- routing ----------------------------------------------------------
    def find_sink(self, endpoint: Endpoint) -> Optional[str]:
        if endpoint.kind != "bluetooth":
            return None
        prefix = "bluez_sink." + endpoint.address.replace(":", "_") + "."
        result = self._pactl("list", "short", "sinks")
        if not result.ok:
            return None
        names = [
            fields[1]
            for fields in (line.split("\t") for line in result.output.splitlines())
            if len(fields) > 1 and fields[1].startswith(prefix)
        ]
        a2dp = [n for n in names if n.endswith(".a2dp_sink")]
        return (a2dp or names or [None])[0]

    def default_sink(self) -> Optional[str]:
        result = self._pactl("info")
        for line in result.output.splitlines():
            if line.startswith("Default Sink:"):
                return line.split(":", 1)[1].strip() or None
        return None

    def route_to(self, sink: str) -> tuple[bool, str]:
        result = self._pactl("set-default-sink", sink)
        if not result.ok:
            return False, f"set-default-sink {sink} failed: {result.output.strip()[:200]}"
        moved = 0
        inputs = self._pactl("list", "short", "sink-inputs")
        for line in inputs.output.splitlines() if inputs.ok else []:
            index = line.split("\t", 1)[0].strip()
            if index.isdigit() and self._pactl("move-sink-input", index, sink).ok:
                moved += 1
        return True, f"default sink {sink}" + (f"; moved {moved} stream(s)" if moved else "")

    # -- isolation --------------------------------------------------------
    def _pulseaudio_pids(self) -> list[tuple[int, int]]:
        """(pid, uid) of every PulseAudio process on the host."""
        found = []
        for entry in self._proc_root.iterdir() if self._proc_root.is_dir() else []:
            if not entry.name.isdigit():
                continue
            try:
                if (entry / "comm").read_text().strip() != "pulseaudio":
                    continue
                uid = next(
                    int(line.split()[1])
                    for line in (entry / "status").read_text().splitlines()
                    if line.startswith("Uid:")
                )
            except (OSError, StopIteration, ValueError):
                continue
            found.append((int(entry.name), uid))
        return found

    def _opens_sound_devices(self, pid: int) -> list[str]:
        fd_dir = self._proc_root / str(pid) / "fd"
        hits = []
        try:
            for fd in fd_dir.iterdir():
                try:
                    target = os.readlink(fd)
                except OSError:
                    continue
                if target.startswith("/dev/snd/"):
                    hits.append(target)
        except OSError:
            pass
        return sorted(set(hits))

    def isolation_violations(self) -> list[str]:
        """Evidence that the server could be holding an ALSA (capture) device."""
        problems = []
        pid = self.managed_pid
        if pid is not None:
            devices = self._opens_sound_devices(pid)
            if devices:
                problems.append(f"managed PulseAudio {pid} has ALSA devices open: {devices}")
        if self._answering():
            modules = self._pactl("list", "short", "modules")
            for line in modules.output.splitlines() if modules.ok else []:
                fields = line.split("\t")
                if len(fields) > 1 and _CAPTURE_RISK_MODULES.match(fields[1]):
                    problems.append(f"PulseAudio loaded {fields[1]}")
        return problems

    def other_servers(self) -> list[dict]:
        """PulseAudio processes this manager does not own (e.g. a desktop session)."""
        own = self.managed_pid
        out = []
        for pid, uid in self._pulseaudio_pids():
            if pid == own:
                continue
            entry = {"pid": pid, "uid": uid}
            devices = self._opens_sound_devices(pid)
            if devices:
                entry["alsa_devices"] = devices
            out.append(entry)
        return out

    def describe(self) -> dict:
        return {
            "type": self.type,
            "user": self.user,
            "socket": str(self.socket) if self.socket else None,
            "managed_pid": self.managed_pid,
            "starts": self.starts,
            "last_exit": self.last_exit,
        }


def build_server(
    config: AudioOutputConfig, needs: FrozenSet[str], runner: Optional[CommandRunner] = None
) -> AudioServer:
    if config.server.type == "pulseaudio":
        assert config.server.pulseaudio is not None
        server = PulseAudioServer(config.server.pulseaudio.user, needs, runner)
    else:
        raise AudioOutputConfigError(f"unsupported server type {config.server.type!r}")
    missing = needs - server.capabilities
    if missing:
        raise AudioOutputConfigError(
            f"audio_output.output.type {config.output.type!r} needs "
            f"{', '.join(sorted(missing))}, which audio_output.server.type "
            f"{config.server.type!r} does not provide"
        )
    return server
